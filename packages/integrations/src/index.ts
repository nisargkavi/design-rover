import type { CanonicalModel } from "@design-rover/model"

/**
 * Maps approved Design Rover conventions onto @shadcn/lint rules.
 * Does not reimplement those rules. @shadcn/lint remains optional.
 *
 * @shadcn/lint is MIT-licensed. Design Rover is not affiliated with shadcn.
 */
export function mapShadcnLint(model: CanonicalModel): {
  availableRules: string[]
  config: Record<string, unknown>
  mapped: { convention: string; rule: string }[]
} {
  const mapped: { convention: string; rule: string }[] = []
  const rules: Record<string, unknown> = {}

  const approved = model.conventions.filter(
    (item) => item.status === "approved" || item.status === "observed",
  )

  // A preference against new abstractions is not a ban on arbitrary values.
  const noArbitrary = approved.find((item) => item.id === "convention.no-arbitrary-values")
  if (noArbitrary) {
    rules["shadcn/no-arbitrary-values"] = "error"
    mapped.push({
      convention: noArbitrary.name,
      rule: "shadcn/no-arbitrary-values",
    })
  }

  const primitives = approved.find((item) => item.id.includes("prefer-existing-primitives"))
  if (primitives) {
    rules["shadcn/no-restyle"] = [
      "error",
      {
        allow: ["layout"],
        message: {
          spacing: "Use an existing component size instead of padding. {{sizes}}",
        },
      },
    ]
    mapped.push({
      convention: primitives.name,
      rule: "shadcn/no-restyle",
    })
  }

  const tokens = model.tokens.filter(
    (item) =>
      (item.status === "approved" || item.status === "observed") &&
      (item.category === "color" || item.category === "semantic-color"),
  )
  if (tokens.length >= 4) {
    rules["shadcn/no-raw-colors"] = "error"
    mapped.push({
      convention: "Named color tokens",
      rule: "shadcn/no-raw-colors",
    })
  }

  const ui = model.components.find((item) => item.source.includes("components/ui/"))
  const settings: Record<string, unknown> = {}
  if (ui?.importPath.startsWith("@/")) {
    const prefix = ui.importPath.split("/").slice(0, 2).join("/")
    settings.ui = prefix
  }

  return {
    availableRules: [
      "shadcn/no-restyle",
      "shadcn/no-raw-colors",
      "shadcn/no-arbitrary-values",
      "shadcn/no-inline-styles",
      "shadcn/no-unknown-classes",
      "shadcn/require-static-classes",
    ],
    config: {
      settings: Object.keys(settings).length ? { shadcn: settings } : undefined,
      rules,
      note: "Generated from Design Rover approved conventions. @shadcn/lint is an optional enforcement engine, not part of Design Rover.",
    },
    mapped,
  }
}

export function oxlintFromMap(mapping: ReturnType<typeof mapShadcnLint>): string {
  return `${JSON.stringify(
    {
      $comment: "Generated by Design Rover from approved conventions. Not affiliated with shadcn.",
      jsPlugins: ["@shadcn/lint"],
      ...(mapping.config.settings ? { settings: mapping.config.settings } : {}),
      rules: mapping.config.rules,
    },
    null,
    2,
  )}\n`
}

export type ExternalSourceInput = {
  kind: "figma" | "storybook" | "docs" | "registry" | "other"
  name: string
  location?: string
  records?: { subject: string; property: string; value: string }[]
}

export function reconcileSources(
  codeValues: { subject: string; property: string; value: string }[],
  incoming: ExternalSourceInput,
) {
  const discrepancies = []
  for (const record of incoming.records ?? []) {
    const code = codeValues.find(
      (item) => item.subject === record.subject && item.property === record.property,
    )
    if (code && code.value !== record.value) {
      discrepancies.push({
        id: `${incoming.kind}:${record.subject}:${record.property}`,
        subject: record.subject,
        property: record.property,
        codeValue: code.value,
        designValue: record.value,
        status: "unresolved" as const,
      })
    }
  }
  return discrepancies
}

export function storybookEvidence(files: string[]): string[] {
  return files.filter((file) => file.includes(".storybook") || file.endsWith(".stories.tsx"))
}
